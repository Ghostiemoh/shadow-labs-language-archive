// Builds supabase/seed.sql from data/concepts.json, data/images.json and data/tasks.json.
// Safe to re-run: concepts upsert by slug; names, photos and tasks are only added once.
//
//   node scripts/build-seed-sql.mjs
import { readFile, writeFile } from "node:fs/promises";

const load = async (p) => JSON.parse(await readFile(new URL(p, import.meta.url)));
const { concepts } = await load("../data/concepts.json");
const images = await load("../data/images.json");
const { tasks } = await load("../data/tasks.json");
const q = (v) => (v === undefined || v === null || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const LANGS = ["ha", "yo", "ig"];

let sql = "-- Generated by scripts/build-seed-sql.mjs. Names are AI drafts awaiting review.\n\n";

sql += "insert into public.concepts (slug, english, gloss, collection_slug) values\n";
sql += concepts.map((c) => `  (${q(c.slug)}, ${q(c.english)}, ${q(c.gloss)}, ${q(c.collection)})`).join(",\n");
sql += "\non conflict (slug) do update set english = excluded.english, gloss = excluded.gloss, collection_slug = excluded.collection_slug;\n\n";

const names = [];
for (const c of concepts) for (const l of LANGS) if (c[l]) names.push(`(${q(c.slug)}, ${q(l)}, ${q(c[l])})`);
sql += `insert into public.lexemes (concept_id, language, form, is_primary, source, status)
select c.id, v.lang, v.form, true, 'ai_draft', 'pending'
from (values\n  ${names.join(",\n  ")}\n) as v(slug, lang, form)
join public.concepts c on c.slug = v.slug
where not exists (select 1 from public.lexemes x where x.concept_id = c.id and x.language = v.lang and x.form = v.form);\n\n`;

const imgs = Object.entries(images).map(([slug, i]) =>
  `(${q(slug)}, ${q(i.url)}, ${q(i.license)}, ${q(i.license_url)}, ${q(i.source_url)}, ${q(i.creator)}, ${q(i.credit)})`);
sql += `insert into public.media (kind, concept_id, url, license, license_url, source_url, creator, credit, is_primary, status)
select 'image', c.id, v.url, v.license, v.license_url, v.source_url, v.creator, v.credit, true, 'approved'
from (values\n  ${imgs.join(",\n  ")}\n) as v(slug, url, license, license_url, source_url, creator, credit)
join public.concepts c on c.slug = v.slug
where not exists (select 1 from public.media m where m.concept_id = c.id and m.url = v.url);\n\n`;

const rows = [];
for (const t of tasks) for (const l of LANGS)
  rows.push(`(${q(t.concept)}, ${q(t.en)}, ${q(l)}, ${q(t[l])}, ${t[l] ? "'claude-draft'" : "null"})`);
sql += `insert into public.tasks (concept_id, source_text, target_language, ai_draft, ai_engine)
select c.id, v.en, v.lang, v.draft, v.engine
from (values\n  ${rows.join(",\n  ")}\n) as v(slug, en, lang, draft, engine)
left join public.concepts c on c.slug = v.slug
where not exists (select 1 from public.tasks t where t.source_text = v.en and t.target_language = v.lang);\n`;

await writeFile(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`seed.sql: ${concepts.length} concepts, ${names.length} names, ${imgs.length} photos, ${rows.length} tasks`);
